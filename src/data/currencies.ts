// Historical rate simulation generator based on realistic volatility
export function generateSimulatedHistory(
  baseRate: number,
  currencyCode: string,
  days: number = 30
): { date: string; rate: number }[] {
  const points: { date: string; rate: number }[] = [];
  const now = new Date();
  
  // Seed with deterministic pseudo-random variation using char codes
  let seed = 0;
  for (let i = 0; i < currencyCode.length; i++) {
    seed += currencyCode.charCodeAt(i);
  }

  // Realistic daily volatility: 0.2% - 0.4%
  const volatility = 0.0035;
  let currentVal = baseRate;

  // Generate backwards from today
  for (let i = days - 1; i >= 0; i--) {
    const d = new Date(now);
    d.setDate(d.getDate() - i);
    const dateStr = d.toLocaleDateString('en-SG', {
      month: 'short',
      day: 'numeric',
    });

    // Sine wave + pseudo noise for natural financial trends
    const wave = Math.sin((i + seed) / 4) * 0.006;
    const noise = (((seed * (i + 13)) % 100) / 100 - 0.5) * volatility;
    const factor = 1 + wave + noise;
    
    // Smooth walking rate
    const simulatedRate = Number((baseRate * factor).toFixed(4));
    points.push({
      date: dateStr,
      rate: i === 0 ? baseRate : simulatedRate,
    });
  }

  return points;
}
